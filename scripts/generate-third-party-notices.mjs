import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { getLicenseFileText } = require("generate-license-file");

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, "THIRD_PARTY_NOTICES.txt");
const electronPackage = JSON.parse(
  readFileSync(path.join(root, "node_modules", "electron", "package.json"), "utf8"),
);
const electronLicense = readFileSync(
  path.join(root, "node_modules", "electron", "LICENSE"),
  "utf8",
).trim();

const dependencyNotices = (
  await getLicenseFileText(path.join(root, "package.json"), {
    lineEnding: "lf",
    // DOMPurify is dual-licensed. Select its Apache-2.0 grant explicitly so
    // generation never depends on license-file discovery order.
    replace: {
      "dompurify": path.join(root, "node_modules", "dompurify", "LICENSE"),
    },
  })
).trim();

const content = `THIRD-PARTY SOFTWARE NOTICES AND INFORMATION

This file is generated by scripts/generate-third-party-notices.mjs.
Do not edit it directly. Run npm run licenses:generate after dependency changes.

${dependencyNotices}

--------------------------------------------------------------------------------
Electron ${electronPackage.version}
--------------------------------------------------------------------------------

Electron is distributed as the desktop runtime even though its npm package is
a development dependency used by electron-builder.

${electronLicense}

The packaged legal resources also include LICENSES.chromium.html from the
Electron distribution. It contains Chromium's bundled third-party notices.
`;

if (process.argv.includes("--check")) {
  let tracked = "";
  try {
    tracked = readFileSync(target, "utf8");
  } catch {
    throw new Error("THIRD_PARTY_NOTICES.txt is missing. Run npm run licenses:generate.");
  }
  if (tracked !== content) {
    throw new Error(
      "THIRD_PARTY_NOTICES.txt is stale. Run npm run licenses:generate and commit the result.",
    );
  }
  console.log("third-party notices: current");
} else {
  writeFileSync(target, content, "utf8");
  console.log("third-party notices: generated");
}
